export const languages = ['pt-BR', 'en', 'es', 'pt-PT'] as const;
export type Language = (typeof languages)[number];
export function resolveLanguage(tag: string | null | undefined): Language {
  if (tag?.toLowerCase().startsWith('pt-pt')) return 'pt-PT';
  if (tag?.toLowerCase().startsWith('en')) return 'en';
  if (tag?.toLowerCase().startsWith('es')) return 'es';
  return 'pt-BR';
}
